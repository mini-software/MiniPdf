        public static uint ArgbFromKnownColor(KnownColor color)
        {
            int idx = (int)color;
            if (idx < 1 || idx > 174)
                return 0xFF000000;
            return s_colorTable[idx];
        }

        public static bool IsSystemColor(KnownColor color)
        {
            int idx = (int)color;
            return (idx >= 1 && idx <= 26) || (idx >= 168 && idx <= 174);
        }
