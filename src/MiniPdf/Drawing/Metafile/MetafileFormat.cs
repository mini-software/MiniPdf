namespace MiniPdf.Drawing.Metafile
{
    /// <summary>
    /// Specifies the format of a metafile.
    /// </summary>
    public enum MetafileFormat
    {
        /// <summary>
        /// Unknown metafile format.
        /// </summary>
        Unknown,

        /// <summary>
        /// Windows Metafile (WMF) format.
        /// </summary>
        Wmf,

        /// <summary>
        /// Enhanced Metafile (EMF) format.
        /// </summary>
        Emf,

        /// <summary>
        /// Enhanced Metafile Plus (EMF+) format.
        /// </summary>
        EmfPlus,
    }
}
