namespace MiniSoftware.Drawing.Text
{
    /// <summary>
    /// Specifies the type of display for hotkey prefixes in text.
    /// </summary>
    public enum HotkeyPrefix
    {
        /// <summary>
        /// No hotkey prefix display.
        /// </summary>
        None = 0,

        /// <summary>
        /// Show hotkey prefixes.
        /// </summary>
        Show = 1,

        /// <summary>
        /// Hide hotkey prefixes.
        /// </summary>
        Hide = 2
    }
}