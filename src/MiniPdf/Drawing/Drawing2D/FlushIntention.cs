namespace MiniPdf.Drawing.Drawing2D
{
    /// <summary>
    /// Specifies whether to flush immediately or synchronize before flushing.
    /// </summary>
    public enum FlushIntention
    {
        /// <summary>
        /// Flush immediately.
        /// </summary>
        Flush = 0,

        /// <summary>
        /// Synchronize before flushing.
        /// </summary>
        Sync = 1
    }
}
