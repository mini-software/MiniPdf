namespace MiniSoftware.Drawing.Drawing2D
{
    /// <summary>
    /// Specifies the alignment of a <see cref="Pen"/> relative to the stroke outline.
    /// </summary>
    public enum PenAlignment
    {
        /// <summary>
        /// The pen stroke is centered on the outline.
        /// </summary>
        Center = 0,

        /// <summary>
        /// The pen stroke is inset from the outline.
        /// </summary>
        Inset  = 1,
    }
}
