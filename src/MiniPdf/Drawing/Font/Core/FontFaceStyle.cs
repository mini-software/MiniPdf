namespace MiniSoftware.Drawing.Font.Core
{
    /// <summary>
    /// Describes the typographic style of a font face.
    /// </summary>
    public enum FontFaceStyle
    {
        /// <summary>
        /// Normal font weight and style.
        /// </summary>
        Regular    = 0,

        /// <summary>
        /// Bold font weight.
        /// </summary>
        Bold       = 1,

        /// <summary>
        /// Italic font style.
        /// </summary>
        Italic     = 2,

        /// <summary>
        /// Bold and italic font weight and style.
        /// </summary>
        BoldItalic = 3,
    }
}